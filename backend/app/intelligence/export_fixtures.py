"""Regenerate SYNTHETIC intelligence fixtures.

    python -m app.intelligence.export_fixtures [output_dir]      (run with backend/ on PYTHONPATH)

Default output: fixtures/v1/intelligence/. Every file is produced from fake
adapters and a synthetic stream; none is a live measurement. IDs and
timestamps change on each run.
"""

from __future__ import annotations

import asyncio
import json
import math
import random
import sys
import uuid
from pathlib import Path

from . import fakes
from .learner import LearnerConfig, StreamingLearner
from .reasoning import MockProvider
from .service import IntelligenceService

HEADER = {"_fixture": "SYNTHETIC - generated by app.intelligence.export_fixtures; not a live measurement"}


class _Req:
    def __init__(self, sql, parameters=None):
        self.sql, self.parameters, self.target_id = sql, parameters or {}, "inventory-lab"


def _write(out: Path, name: str, obj) -> None:
    data = obj.model_dump(mode="json") if hasattr(obj, "model_dump") else obj
    out.joinpath(name).write_text(json.dumps({**HEADER, "data": data}, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _synthetic_stream(learner: StreamingLearner, n: int, rng: random.Random, scale: float = 1.0) -> None:
    from datetime import datetime, timezone

    from app.contracts import LearningObservation

    for _ in range(n):
        rows = rng.uniform(0, 10)
        rid = f"req_{uuid.uuid4().hex}"
        learner.register_arrival(
            rid, {"log_est_rows": rows, "log_est_bytes": rows + 4, "log_planner_cost": rows * 0.8, "plan_seq_scan": float(rows > 5), "ready_fraction": 1.0}, learner.source
        )
        ms = scale * math.expm1(0.6 * rows + 1.0) * rng.uniform(0.9, 1.1)
        learner.observe(
            LearningObservation(
                source=learner.source, request_id=rid, captured_at=datetime.now(timezone.utc), state_id="synthetic",
                kind="completed", features=None, duration_ms=ms, output_rows=None, active_fault_id=None,
            )
        )


async def _main(out: Path) -> None:
    allow = fakes.lab_allowlist()
    est = fakes.FakePlanEstimator(allow)
    svc = IntelligenceService(allow, learner=StreamingLearner(source="fixture"))

    async def decide(sql, params=None, state=None, estimator=est):
        return await svc.analyze_query(_Req(sql, params), state or fakes.state(), estimator)

    _write(out, "query_decision_allow.json", await decide("SELECT id, name, price_cents FROM lab.products WHERE id = $1", {"1": 42}))
    _write(out, "query_decision_warn_sort.json", await decide("SELECT id, name FROM lab.products ORDER BY name LIMIT 10"))
    _write(out, "query_decision_warn_stale_state.json", await decide("SELECT id FROM lab.products WHERE id = $1", {"1": 1}, fakes.state(stale=True)))
    _write(out, "query_decision_block_unbounded.json", await decide("SELECT * FROM lab.products"))
    _write(out, "query_decision_block_write.json", await decide("DELETE FROM lab.products"))
    _write(
        out,
        "query_decision_block_unknown_estimate.json",
        await decide("SELECT id FROM lab.products WHERE id = $1", {"1": 1}, estimator=fakes.FakePlanEstimator(allow, unavailable=True)),
    )
    _write(out, "learning_status_cold_start.json", await svc.get_learning_status())

    warm = StreamingLearner(source="fixture")
    _synthetic_stream(warm, 300, random.Random(5))
    _write(out, "learning_status_after_300_synthetic.json", warm.status())

    drift = StreamingLearner(LearnerConfig(drift_action="flag"), source="fixture")
    rng = random.Random(11)
    _synthetic_stream(drift, 200, rng)
    _synthetic_stream(drift, 8, rng, scale=200.0)  # flagged at the 8th shifted sample; the model re-adapts by ~10
    _write(out, "learning_status_drift.json", drift.status())

    topo = fakes.topology()
    _write(out, "experiment_proposals.json", [p.model_dump(mode="json") for p in await svc.plan(topo, fakes.state(), fakes.catalog(), {})])
    supported = fakes.run_summary()
    svc.note_run_target(supported.run_id, "productcatalogservice")
    _write(out, "analysis_supported.json", await svc.analyze_run(supported, topo))
    _write(out, "analysis_insufficient_evidence.json", await svc.analyze_run(fakes.run_summary(samples=5), topo))
    outage = IntelligenceService(allow, provider=MockProvider([ConnectionError("down"), ConnectionError("down")]))
    _write(out, "analysis_model_outage.json", await outage.analyze_run(fakes.run_summary(), topo))


def main(out_dir: str = "fixtures/v1/intelligence") -> list[str]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    asyncio.run(_main(out))
    return sorted(p.name for p in out.iterdir())


if __name__ == "__main__":
    for name in main(*sys.argv[1:]):
        print(name)
