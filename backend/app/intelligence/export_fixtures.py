"""Regenerate SYNTHETIC intelligence fixtures.

    python -m app.intelligence.export_fixtures [output_dir]      (run with backend/ on PYTHONPATH)

Default output: fixtures/v1/intelligence/. Every file is produced from fake
adapters and a synthetic stream; none is a live measurement. IDs and
timestamps change on each run.
"""

from __future__ import annotations

import asyncio
import json
import math
import random
import sys
import uuid
from pathlib import Path

from . import fakes
from .reasoning import MockProvider
from .service import IntelligenceService

HEADER = {"_fixture": "SYNTHETIC - generated by app.intelligence.export_fixtures; not a live measurement"}


def _write(out: Path, name: str, obj) -> None:
    data = obj.model_dump(mode="json") if hasattr(obj, "model_dump") else obj
    out.joinpath(name).write_text(json.dumps({**HEADER, "data": data}, indent=2, sort_keys=True) + "\n", encoding="utf-8")


async def _main(out: Path) -> None:
    svc = IntelligenceService()

    topo = fakes.topology()
    _write(out, "experiment_proposals.json", [p.model_dump(mode="json") for p in await svc.plan(topo, fakes.state(), fakes.catalog(), {})])
    supported = fakes.run_summary()
    svc.note_run_target(supported.run_id, "productcatalogservice")
    _write(out, "analysis_supported.json", await svc.analyze_run(supported, topo))
    _write(out, "analysis_insufficient_evidence.json", await svc.analyze_run(fakes.run_summary(samples=5), topo))
    outage = IntelligenceService(provider=MockProvider([ConnectionError("down"), ConnectionError("down")]))
    _write(out, "analysis_model_outage.json", await outage.analyze_run(fakes.run_summary(), topo))


def main(out_dir: str = "fixtures/v1/intelligence") -> list[str]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    asyncio.run(_main(out))
    return sorted(p.name for p in out.iterdir())


if __name__ == "__main__":
    for name in main(*sys.argv[1:]):
        print(name)
