"""Owner integration boundary. No policy, metric math or mutations in handlers."""
from dataclasses import dataclass
from typing import Protocol
from app.contracts import *


class PlatformPort(Protocol):
    async def get_topology(self, sandbox_id: str) -> TopologySnapshot: ...
    async def get_target(self, target_id: str) -> VerifiedTarget: ...


class TelemetryPort(Protocol):
    async def get_state(self, sandbox_id: str) -> SystemStateSnapshot: ...
    async def begin_phase(self, run_id: str, phase: str, load_profile: LoadProfile) -> str: ...
    async def close_phase(self, phase_handle: str) -> PhaseSummary: ...
    async def finalize_run(self, run_id: str, runtime_facts: dict) -> RunSummary: ...


class IntelligencePort(Protocol):
    async def plan(self, topology: TopologySnapshot, state: SystemStateSnapshot, catalog: Catalog, coverage: dict) -> list[ExperimentProposal]: ...
    async def analyze_run(self, summary: RunSummary, topology: TopologySnapshot) -> AnalysisResult: ...


class RuntimePort(Protocol):
    async def catalog(self) -> Catalog: ...
    async def validate(self, proposal: ExperimentProposal) -> ValidationResult: ...
    async def approve(self, proposal_id: str, actor: str, proposal_hash: str) -> ApprovalRecord: ...
    async def start(self, proposal_id: str, approval_id: str, idempotency_key: str, actor: str) -> RunHandle: ...
    async def status(self, run_id: str) -> RunStatus: ...
    async def events(self, run_id: str, after_sequence: int) -> list[RunEvent]: ...
    async def stop(self, run_id: str, actor: str) -> StopReceipt: ...
    async def emergency_stop(self, sandbox_id: str, actor: str) -> StopReceipt: ...
    async def reconcile(self, sandbox_id: str) -> CleanupSummary: ...
    async def reset(self, sandbox_id: str, actor: str) -> CleanupSummary: ...


@dataclass
class Ports:
    platform: PlatformPort
    telemetry: TelemetryPort
    intelligence: IntelligencePort
    runtime: RuntimePort
    # Adapter factory explicitly attests independent watchdog/reconciliation readiness.
    runtime_safety_ready: bool = False
